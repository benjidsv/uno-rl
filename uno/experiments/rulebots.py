"""Step 10C cheap rulebots: exact transfer, sampled scores, behavior, and diversity.

    uv run uno rulebots [games=1000] [out_dir=docs/results/figures] [probe_games=300] [dev|eval]
    uv run uno rulebots select [out_dir=docs/results/figures]

Toy profiles are exact. Full-UNO defaults to the DEV selection harness; the
explicit `eval` mode uses the frozen policies on EVAL block 03. Every row agent
plays Random and the Heuristic from both seats on the same deals. Traces are
reduced into mergeable behavior counters one game at a time and discarded. The
common-state diversity panel always uses a bounded DEV probe bank generated by
a fixed Heuristic-vs-Random profile, so evaluated agents cannot look diverse
merely because they steer themselves into different positions.
"""

