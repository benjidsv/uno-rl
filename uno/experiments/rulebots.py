DISPLAY = {
    "random": "Random",
    "heuristic": "Heuristic",
    "heuristic_memory": "Memory ablation",
    "rulebot_transfer_toy_v1": "Transfer bot",
    "rulebot_full_dev_v1": "Full-UNO DEV bot",
}


# The complete bounded manual coordinate sweep used for the toy-only selection.
# Stage 1 changes one feature family around RuleWeights(); stage 2 refines the
# best denial/singleton region. Keeping it out of the default figure command
# avoids adding roughly two minutes of uncached tabulation to every graph rerun.
TRANSFER_SWEEP = (
    ("initial", {}),
    ("denial_0", {"denial": 0.0}),
    ("denial_0.5", {"denial": 0.5}),
    ("denial_1", {"denial": 1.0}),
    ("denial_2.5", {"denial": 2.5}),
    ("singleton_0", {"singleton": 0.0}),
    ("singleton_0.5", {"singleton": 0.5}),
    ("singleton_1", {"singleton": 1.0}),
    ("action_low", {"block_switch": 0.5, "draw_two": 1.0}),
    ("action_high", {"block_switch": 1.5, "draw_two": 2.0}),
    ("followup_0.3", {"followup": 0.3}),
    ("followup_1", {"followup": 1.0}),
    ("wild_hold_-1", {"wild_hold": -1.0}),
    ("wild_hold_-3", {"wild_hold": -3.0}),
    ("denial_2_singleton_0", {"denial": 2.0, "singleton": 0.0}),
    ("denial_2.5_singleton_0", {"denial": 2.5, "singleton": 0.0}),
    ("denial_3_singleton_0", {"denial": 3.0, "singleton": 0.0}),
    ("denial_3", {"denial": 3.0}),
    ("denial_4", {"denial": 4.0}),
)


def agents(rs) -> dict[str, object]:
    base = {"random": PlayFirstRandom(rs), "heuristic": Heuristic(rs)}
    base.update(rulebot_league(rs))
    return base


def label(name: str) -> str:
    return DISPLAY.get(name, "Unpredictable" if name.startswith("rulebot_unpredictable_") else name)


def evaluate(rs, rows: dict[str, object], columns: dict[str, object], seeds) -> tuple[np.ndarray, np.ndarray, np.ndarray, dict[str, BehaviorStats], np.ndarray]:
    """Scores, SEs, per-deal samples, behavior per row, and ms/game."""

    seeds = tuple(seeds)
    samples = np.zeros((len(rows), len(columns), 2, len(seeds)))
    costs = np.zeros(len(rows))
    stats = {name: BehaviorStats() for name in rows}
    for i, (name, row) in enumerate(rows.items()):
        t0 = time.perf_counter()
        for j, col in enumerate(columns.values()):
            for k, seed in enumerate(seeds):
                for seat in (0, 1):
                    pair = (row, col) if seat == 0 else (col, row)
                    trace = play_game(rs, seed, pair)
                    samples[i, j, seat, k] = (returns(trace.final)[seat] + 1.0) / 2.0
                    observe_trace(rs, trace, seat, stats[name])
        row_score = samples[i].mean(axis=2)
        costs[i] = 1000 * (time.perf_counter() - t0) / (len(columns) * 2 * len(seeds))
        print(
            f"   {label(name):20s}  vs Random {row_score[0, 0]:.4f}/{row_score[0, 1]:.4f}"
            f"  vs Heuristic {row_score[1, 0]:.4f}/{row_score[1, 1]:.4f}  {costs[i]:.3f} ms/game",
            flush=True,
        )
    score = samples.mean(axis=3)
    score_se = samples.std(axis=3, ddof=1) / np.sqrt(len(seeds)) if len(seeds) > 1 else np.full(samples.shape[:3], np.nan)
    return score, score_se, samples, stats, costs


def exact_toys() -> tuple[list[str], list[str], np.ndarray]:
    """Exact L1 profile scores for the three Step-11 diagnostic toys.

    The transfer weights were selected only on TOY and TOY2_SKIP. TOY_FULL is
    still displayed: deterministic play-first candidates coincide with TOY
    there, while the unpredictable bot's legal pass behavior does not.
    """

    toy_names = ["TOY", "TOY_FULL", "TOY2_SKIP"]
    values = []
    row_names: list[str] | None = None
    for toy_name in toy_names:
        rs = getattr(rules, toy_name)
        tree = store.load_or_compile(rs, (Level.L1,), symmetric=True)
        rows = agents(rs)
        columns = {name: rows[name] for name in ("random", "heuristic")}
        strategies = {name: (Level.L1, store.load_or_tabulate(tree, Level.L1, agent)) for name, agent in rows.items()}
        score = np.zeros((len(rows), len(columns), 2))
        for i, name in enumerate(rows):
            for j, col in enumerate(columns):
                score[i, j, 0] = (exact_evaluate(tree, strategies[name], strategies[col])[0] + 1.0) / 2.0
                score[i, j, 1] = (exact_evaluate(tree, strategies[col], strategies[name])[1] + 1.0) / 2.0
        values.append(score)
        row_names = list(rows)
    return row_names or [], toy_names, np.stack(values)


def select_transfer(out_dir: Path) -> None:
    """Reproduce the exact toy-only coordinate sweep and assert its winner."""

    data = []
    for toy_name in ("TOY", "TOY2_SKIP"):
        rs = getattr(rules, toy_name)
        tree = store.load_or_compile(rs, (Level.L1,), symmetric=True)
        columns = []
        for agent in (PlayFirstRandom(rs), Heuristic(rs)):
            columns.append((agent.name, (Level.L1, store.load_or_tabulate(tree, Level.L1, agent))))
        data.append((toy_name, rs, tree, columns))

    rows = []
    for candidate, changes in TRANSFER_SWEEP:
        weights = replace(RuleWeights(), **changes)
        cells = {}
        for toy_name, rs, tree, columns in data:
            strategy = (Level.L1, tabulate(tree, Level.L1, TacticalRuleBot(rs, weights, f"transfer_select_{candidate}")))
            for opponent, column in columns:
                cells[(toy_name, opponent, 0)] = (exact_evaluate(tree, strategy, column)[0] + 1.0) / 2.0
                cells[(toy_name, opponent, 1)] = (exact_evaluate(tree, column, strategy)[1] + 1.0) / 2.0
        objective = float(np.mean(list(cells.values())))
        rows.append((candidate, changes, weights, objective, cells))
        print(f"   {candidate:26s} {objective:.6f}", flush=True)

    winner = max(rows, key=lambda row: row[3])
    if winner[2] != TRANSFER_WEIGHTS:
        raise AssertionError(f"recorded transfer weights are not the sweep winner: {winner[0]} {winner[2]}")
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / "rulebot-transfer-selection.csv"
    with path.open("w", newline="") as f:
        fields = ["candidate", "changes", "objective"] + [f"{toy}_{opp}_s{seat}" for toy in ("TOY", "TOY2_SKIP") for opp in ("random", "heuristic") for seat in (0, 1)]
        w = csv.writer(f)
        w.writerow(fields)
        for candidate, changes, _, objective, cells in rows:
            w.writerow((candidate, repr(changes), objective, *(cells[(toy, opp, seat)] for toy in ("TOY", "TOY2_SKIP") for opp in ("random", "heuristic") for seat in (0, 1))))
    print(f"== selected {winner[0]} at {winner[3]:.6f}; wrote {path}")


def probe_bank(rs, games: int, cap: int = 200):
    rnd, heu = PlayFirstRandom(rs), Heuristic(rs)
    buckets = {}
    for seed in seed_registry.dev_block(100_000, games):
        collect_probes(rs, play_game(rs, seed, (heu, rnd)), buckets, cap)
        collect_probes(rs, play_game(rs, seed, (rnd, heu)), buckets, cap)
        if buckets and all(len(x) >= cap for x in buckets.values()) and len(buckets) >= 5:
            break
    probes = [x for rows in buckets.values() for x in rows]
    print("   common probes: " + ", ".join(f"{k}={len(v)}" for k, v in sorted(buckets.items())))
    return probes


def _annotated_heatmap(ax, values, rows, columns, title, vmin=0.0, vmax=1.0, fmt=".0%"):
    im = ax.imshow(values, vmin=vmin, vmax=vmax, cmap="viridis", aspect="auto")
    ax.set_xticks(range(len(columns)))
    ax.set_xticklabels(columns, rotation=35, ha="right", fontsize=8)
    ax.set_yticks(range(len(rows)))
    ax.set_yticklabels(rows, fontsize=8)
    ax.set_title(title, fontsize=10)
    for i in range(values.shape[0]):
        for j in range(values.shape[1]):
            x = values[i, j]
            text = ".." if not np.isfinite(x) else format(x, fmt)
            colour = "white" if np.isfinite(x) and x > (vmin + vmax) / 2 else "black"
            ax.text(j, i, text, ha="center", va="center", fontsize=7, color=colour)
    return im


def fig_toy_transfer(names, toy_names, score, path: Path) -> None:
    row_labels = [label(n) for n in names]
    columns = ["vs Random s0", "vs Random s1", "vs Heuristic s0", "vs Heuristic s1"]
    fig, axes = plt.subplots(1, len(toy_names), figsize=(15.5, 5.8), sharey=True)
    for i, (toy, ax) in enumerate(zip(toy_names, axes)):
        values = score[i][:, [0, 0, 1, 1], [0, 1, 0, 1]]
        im = _annotated_heatmap(ax, values, row_labels, columns, toy, vmin=0.25, vmax=0.75, fmt=".3f")
        ax.set_xlabel("exact profile")
    axes[0].set_ylabel("row agent")
    fig.colorbar(im, ax=axes, fraction=0.02, pad=0.025, label="exact score")
    fig.suptitle("Exact toy transfer check (TOY and TOY2_SKIP are the selection set)")
    fig.subplots_adjust(bottom=0.23, top=0.87, wspace=0.08)
    fig.savefig(path, format="svg")
    plt.close(fig)


def fig_strength(names, columns, score, costs, sample_label: str, path: Path) -> None:
    fig, axes = plt.subplots(1, 2, figsize=(10.5, 5.7), sharey=True)
    row_labels = [f"{label(n)}  ({c:.2f} ms/game)" for n, c in zip(names, costs)]
    for seat, ax in enumerate(axes):
        im = _annotated_heatmap(ax, score[:, :, seat], row_labels, [label(x) for x in columns], f"row score at seat {seat}", vmin=0.35, vmax=0.65, fmt=".3f")
        ax.set_xlabel("opponent")
    axes[0].set_ylabel("row agent")
    fig.colorbar(im, ax=axes, fraction=0.03, pad=0.03, label="score")
    fig.suptitle(f"Step 10C cheap rulebots: strength on {sample_label} (cell SEs in CSV)")
    fig.subplots_adjust(left=0.23, bottom=0.2, top=0.88, wspace=0.08)
    fig.savefig(path, format="svg")
    plt.close(fig)


RATE_LABELS = {
    "voluntary_draw": "draw | play",
    "draw_with_wild": "draw | wild",
    "keep_drawn": "keep drawn",
    "keep_drawn_wild": "keep drawn wild",
    "wild_hoard": "hoard wild",
    "wild4_hoard": "hoard +4",
    "draw_two_use": "use +2",
    "block_switch_use": "use skip/reverse",
    "sustainable_action": "sustainable action",
    "void_target": "target void",
    "normalised_entropy": "policy entropy",
    "deterministic": "deterministic",
}


def fig_behavior(names, stats: dict[str, BehaviorStats], sample_label: str, path: Path) -> None:
    row_labels = [label(n) for n in names]
    rates = np.array([[stats[n].rate(m) for m in RATE_METRICS] for n in names])
    counts = np.array([[stats[n].per_game(m) for m in COUNT_METRICS] for n in names])
    count_max = float(np.nanmax(counts)) if counts.size else 1.0
    fig, axes = plt.subplots(1, 2, figsize=(17, 6.2), gridspec_kw={"width_ratios": [2.35, 1]})
    a = _annotated_heatmap(axes[0], rates, row_labels, [RATE_LABELS[x] for x in RATE_METRICS], "conditional policy rates (expected probability mass)")
    b = _annotated_heatmap(axes[1], counts, row_labels, [x.replace("_", " ") + "/game" for x in COUNT_METRICS], "realised game counts", vmax=count_max, fmt=".2f")
    fig.colorbar(a, ax=axes[0], fraction=0.02, pad=0.02, label="conditional rate")
    fig.colorbar(b, ax=axes[1], fraction=0.04, pad=0.02, label="count per game")
    fig.suptitle(f"Behavioral fingerprints on {sample_label}: opportunity-normalised choices and realised counts")
    fig.subplots_adjust(bottom=0.24, top=0.88, wspace=0.17)
    fig.savefig(path, format="svg")
    plt.close(fig)


def fig_diversity(names, distance, path: Path) -> None:
    labels = [label(n) for n in names]
    fig, ax = plt.subplots(figsize=(7.8, 6.8))
    im = _annotated_heatmap(ax, distance, labels, labels, "Common-state policy distance\n(node kinds weighted equally)", vmax=max(0.5, float(distance.max())), fmt=".2f")
    fig.colorbar(im, ax=ax, fraction=0.04, pad=0.03, label="mean total-variation distance")
    fig.tight_layout()
    fig.savefig(path, format="svg")
    plt.close(fig)


def write_tables(out_dir: Path, names, columns, score, score_se, samples, costs, stats, distance, toy_names, toy_score, games: int, sample_label: str) -> None:
    with (out_dir / "rulebot-behavior.csv").open("w", newline="") as f:
        fields = ["sample", "agent", "ms_per_game", *RATE_METRICS, *[f"{x}_per_game" for x in COUNT_METRICS], *[f"n_{x}" for x in RATE_METRICS]]
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        for i, name in enumerate(names):
            s = stats[name]
            row = {"sample": sample_label, "agent": name, "ms_per_game": costs[i]}
            row.update(s.rates())
            row.update({f"{k}_per_game": v for k, v in s.counts().items()})
            row.update({f"n_{k}": s.denominators[k] for k in RATE_METRICS})
            w.writerow(row)
    with (out_dir / "rulebot-scores.csv").open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(("sample", "agent", "opponent", "seat", "score", "se", "games"))
        for i, name in enumerate(names):
            for j, col in enumerate(columns):
                for seat in (0, 1):
                    w.writerow((sample_label, name, col, seat, score[i, j, seat], score_se[i, j, seat], games))
    with (out_dir / "rulebot-deltas.csv").open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(("sample", "agent", "reference", "opponent", "seat", "paired_delta", "se", "z", "games"))
        ref = names.index("heuristic")
        for i, name in enumerate(names):
            for j, col in enumerate(columns):
                for seat in (0, 1):
                    delta = samples[i, j, seat] - samples[ref, j, seat]
                    mean = float(delta.mean())
                    se = float(delta.std(ddof=1) / np.sqrt(len(delta))) if len(delta) > 1 else float("nan")
                    z = mean / se if se > 0 else float("nan")
                    w.writerow((sample_label, name, "heuristic", col, seat, mean, se, z, games))
    with (out_dir / "rulebot-toy-scores.csv").open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(("ruleset", "agent", "opponent", "seat", "exact_score", "ruleset_in_transfer_selection"))
        for k, toy in enumerate(toy_names):
            for i, name in enumerate(names):
                for j, col in enumerate(columns):
                    for seat in (0, 1):
                        w.writerow((toy, name, col, seat, toy_score[k, i, j, seat], toy in ("TOY", "TOY2_SKIP")))
    with (out_dir / "rulebot-policy-distance.csv").open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(("agent", *names))
        for name, row in zip(names, distance):
            w.writerow((name, *row))


def main(argv: list[str] | None = None) -> None:
    argv = sys.argv[1:] if argv is None else argv
    if argv and argv[0] == "select":
        select_transfer(Path(argv[1]) if len(argv) > 1 else Path("docs/results/figures"))
        return
    games = int(argv[0]) if argv else 1000
    out_dir = Path(argv[1]) if len(argv) > 1 else Path("docs/results/figures")
    probe_games = int(argv[2]) if len(argv) > 2 else min(games, 300)
    sample = argv[3] if len(argv) > 3 else "dev"
    out_dir.mkdir(parents=True, exist_ok=True)
    rs = rules.FULL_UNO
    rows = agents(rs)
    columns = {"random": rows["random"], "heuristic": rows["heuristic"]}
    if sample == "dev":
        seeds = seed_registry.dev_block(0, games)
        sample_label = "DEV deals"
    elif sample == "eval":
        block = seed_registry.block("03")
        if games > len(block):
            raise ValueError(f"EVAL block 03 has only {len(block)} deals")
        seeds = block[:games]
        sample_label = "EVAL block 03"
    else:
        raise ValueError(f"unknown sample {sample!r}: expected dev or eval")
    print(f"== step 10C cheap rulebots: {games} {sample_label}, both seats, vs Random and Heuristic")
    toy_agent_names, toy_names, toy_score = exact_toys()
    if toy_agent_names != list(rows):
        raise AssertionError("toy and full-UNO agent order differ")
    score, score_se, samples, stats, costs = evaluate(rs, rows, columns, seeds)
    probes = probe_bank(rs, probe_games)
    names, distance = policy_distances(rows, probes)

    print("\n== behavioral fingerprint (conditional rates; '..' means no opportunity)")
    print(f"   {'agent':20s} " + " ".join(f"{RATE_LABELS[x]:>11.11s}" for x in RATE_METRICS))
    for name in names:
        cells = [".." if not np.isfinite(stats[name].rate(x)) else f"{100 * stats[name].rate(x):10.1f}%" for x in RATE_METRICS]
        print(f"   {label(name):20s} " + " ".join(cells))

    write_tables(out_dir, names, list(columns), score, score_se, samples, costs, stats, distance, toy_names, toy_score, games, sample_label)
    fig_toy_transfer(names, toy_names, toy_score, out_dir / "09-rulebot-toy-transfer.svg")
    fig_strength(names, list(columns), score, costs, sample_label, out_dir / "10-rulebot-strength.svg")
    fig_behavior(names, stats, sample_label, out_dir / "11-rulebot-behavior.svg")
    fig_diversity(names, distance, out_dir / "12-rulebot-diversity.svg")
    print("\n== wrote")
    for name in ("09-rulebot-toy-transfer.svg", "10-rulebot-strength.svg", "11-rulebot-behavior.svg", "12-rulebot-diversity.svg", "rulebot-behavior.csv", "rulebot-scores.csv", "rulebot-deltas.csv", "rulebot-toy-scores.csv", "rulebot-policy-distance.csv"):
        print(f"   {out_dir / name}")


if __name__ == "__main__":
    main()
